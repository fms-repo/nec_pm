-- Migration 2026-11-05-011: dated actual-quantity entries on materials and crew / labour lines
-- Runs once, inside a transaction (if any statement fails, none of it is applied).
--
-- A line's Actual Qty (material "Consumed Qty", crew "Actual Qty") can be typed directly, or built up over time from dated
-- entries. The stored actual quantity on the line stays the single total either way; these rows are the dated history behind
-- it. Lines are rewritten on every project save, so each save re-creates its entries against the new line ids.
CREATE TABLE IF NOT EXISTS line_actual_entries (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  line_kind   TEXT NOT NULL CHECK (line_kind IN ('material', 'crew')),
  line_id     INTEGER NOT NULL,
  entry_date  TEXT NOT NULL,
  quantity    DOUBLE PRECISION NOT NULL,
  note        TEXT,
  created_by  TEXT,
  created_at  TEXT NOT NULL DEFAULT utc_now_text()
);
CREATE INDEX IF NOT EXISTS idx_line_actual_entries_project ON line_actual_entries(project_id);
CREATE INDEX IF NOT EXISTS idx_line_actual_entries_line ON line_actual_entries(line_kind, line_id);
