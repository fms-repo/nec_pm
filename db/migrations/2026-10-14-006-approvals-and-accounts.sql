-- Migration 2026-10-14-006: personal user accounts + document approval workflow
-- Runs once, inside a transaction (if any statement fails, none of it is applied).
--
-- 1. Personal accounts. A team member can be given a login (username + hashed password). The
--    shared APP_USERNAME/APP_PASSWORD login keeps working as the administrator account.
-- 2. Approvals. VOWD statements, change requests and completion certificates can be sent for
--    sign-off to specific team members, in sequence. Every step is stored (who, when, comment, IP)
--    and never deleted; a resubmission after a rejection starts a new round.

-- Kept in its own table (not columns on team_members) so credentials can never ride along in
-- the many `SELECT *` team-member responses or in audit-log row snapshots.
CREATE TABLE IF NOT EXISTS user_accounts (
  team_member_id      INTEGER PRIMARY KEY REFERENCES team_members(id) ON DELETE CASCADE,
  username            TEXT NOT NULL,
  password_hash       TEXT NOT NULL,        -- scrypt$N$r$p$salt$hash — never the password itself
  active              INTEGER NOT NULL DEFAULT 1,
  must_change_password INTEGER NOT NULL DEFAULT 1,
  failed_logins       INTEGER NOT NULL DEFAULT 0,
  locked_until        TEXT,
  last_login_at       TEXT,
  password_changed_at TEXT,
  created_at          TEXT NOT NULL DEFAULT utc_now_text()
);
CREATE UNIQUE INDEX IF NOT EXISTS user_accounts_username_uq ON user_accounts (LOWER(username));

-- Where each document stands in the approval workflow:
--   None      never submitted (behaves exactly as before: freely editable)
--   Pending   submitted and waiting on the approvers — content is locked
--   Approved  every approver signed — content stays locked
--   Rejected  an approver rejected it — editable again, then resubmit (new round)
ALTER TABLE vowd_statements         ADD COLUMN IF NOT EXISTS approval_status       TEXT NOT NULL DEFAULT 'None';
ALTER TABLE vowd_statements         ADD COLUMN IF NOT EXISTS approval_round        INTEGER NOT NULL DEFAULT 0;
ALTER TABLE change_requests         ADD COLUMN IF NOT EXISTS approval_status       TEXT NOT NULL DEFAULT 'None';
ALTER TABLE change_requests         ADD COLUMN IF NOT EXISTS approval_round        INTEGER NOT NULL DEFAULT 0;
ALTER TABLE completion_certificates ADD COLUMN IF NOT EXISTS approval_status       TEXT NOT NULL DEFAULT 'None';
ALTER TABLE completion_certificates ADD COLUMN IF NOT EXISTS approval_round        INTEGER NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS document_approval_steps (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id          INTEGER NOT NULL,       -- no FK: removed together with the project on permanent delete
  doc_type            TEXT NOT NULL,          -- vowd | change_request | certificate
  doc_id              INTEGER NOT NULL,
  round               INTEGER NOT NULL DEFAULT 0,  -- 0 = approvers chosen but not yet submitted
  step_no             INTEGER NOT NULL,       -- signing order within the round
  role_key            TEXT NOT NULL,          -- which signature block on the print this fills
  role_label          TEXT NOT NULL,
  team_member_id      INTEGER NOT NULL REFERENCES team_members(id),
  approver_name       TEXT NOT NULL,          -- name/designation as at assignment (the printed record)
  approver_designation TEXT,
  status              TEXT NOT NULL DEFAULT 'Draft',  -- Draft | Pending | Approved | Rejected | Voided
  submitted_at        TEXT,
  submitted_by        TEXT,
  acted_at            TEXT,
  acted_by            TEXT,                   -- username that actually signed
  comment             TEXT,
  ip_address          TEXT,
  created_at          TEXT NOT NULL DEFAULT utc_now_text()
);
CREATE INDEX IF NOT EXISTS approval_steps_doc_idx    ON document_approval_steps (doc_type, doc_id, round, step_no);
CREATE INDEX IF NOT EXISTS approval_steps_member_idx ON document_approval_steps (team_member_id, status);
CREATE INDEX IF NOT EXISTS approval_steps_project_idx ON document_approval_steps (project_id);

-- A change request that completes its approval records the Change Control Board's "Approved" decision
-- itself; this flag marks those rows so that reopening the CR can remove exactly them.
ALTER TABLE change_decisions ADD COLUMN IF NOT EXISTS created_by_approval INTEGER NOT NULL DEFAULT 0;
