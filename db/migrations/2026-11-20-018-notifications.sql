-- Migration 2026-11-20-018: in-app notifications (events past their planned finish, projects falling behind plan)
-- Runs once, inside a transaction.
--
-- The server checks the projects regularly (and right after a project is saved) and writes a row here when:
--   · an event is still open after its planned finish date            (kind 'event-overdue')
--   · a project's progress variance (actual % - planned %) falls below -10 points   (kind 'progress-behind')
-- Each alert is written once: dedup_key is unique. Read state is kept per person, so one person reading an alert does not
-- clear it for anyone else. Who can see an alert follows the project access they already have.

CREATE TABLE IF NOT EXISTS notifications (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind        TEXT NOT NULL,
  dedup_key   TEXT NOT NULL UNIQUE,
  project_id  INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  severity    TEXT NOT NULL DEFAULT 'warn',
  title       TEXT NOT NULL,
  message     TEXT NOT NULL,
  details     TEXT,
  created_at  TEXT NOT NULL DEFAULT utc_now_text()
);
CREATE INDEX IF NOT EXISTS idx_notifications_project ON notifications(project_id);

CREATE TABLE IF NOT EXISTS notification_reads (
  notification_id  INTEGER NOT NULL REFERENCES notifications(id) ON DELETE CASCADE,
  username         TEXT NOT NULL,
  read_at          TEXT NOT NULL DEFAULT utc_now_text(),
  PRIMARY KEY (notification_id, username)
);

-- Whether a project is currently below the -10 point line, so the progress alert fires once when it crosses and again
-- only after the project has recovered and fallen behind a second time.
CREATE TABLE IF NOT EXISTS project_alert_state (
  project_id      INTEGER PRIMARY KEY REFERENCES projects(id) ON DELETE CASCADE,
  progress_below  BOOLEAN NOT NULL DEFAULT FALSE
);
