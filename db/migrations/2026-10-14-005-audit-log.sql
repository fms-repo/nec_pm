-- Runs once, inside a transaction (if any statement fails, none of it is applied).
--
-- One row per user action: sign-in (incl. failed attempts) / sign-out, and every create,
-- update, delete, restore and permanent delete made through the app. Append-only — the app
-- never updates or deletes these rows. No foreign keys on purpose: an entry must outlive the
-- record it describes (e.g. after a project is permanently deleted).
CREATE TABLE IF NOT EXISTS audit_log (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at   TEXT NOT NULL DEFAULT utc_now_text(),
  username      TEXT,
  ip_address    TEXT,
  action        TEXT NOT NULL,  -- login | login_failed | logout | create | update | delete | restore | purge
  entity_type   TEXT,           -- e.g. 'Project', 'Invoice', 'Risk'
  entity_id     INTEGER,
  entity_label  TEXT,           -- the record's code/number/name at the time, e.g. 'INV-P-0003-0002'
  project_id    INTEGER,
  method        TEXT,
  path          TEXT,
  details       TEXT            -- JSON: { changes: {field: [old, new]} } | { values } | { snapshot } | { note }
);
CREATE INDEX IF NOT EXISTS audit_log_occurred_idx ON audit_log (occurred_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS audit_log_project_idx  ON audit_log (project_id);
CREATE INDEX IF NOT EXISTS audit_log_user_idx     ON audit_log (username);
