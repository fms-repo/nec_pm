-- Migration 2026-11-05-012: Report Library
-- Runs once, inside a transaction (if any statement fails, none of it is applied).
--
--   report_runs          every report ever generated, stored as a frozen snapshot (JSON) so the archive shows the
--                        numbers as they were on the day, not as they are today
--   report_run_projects  which projects a run covers (lets the archive be searched by project and lets the app
--                        show a run only to people who may see ALL of its projects). No foreign key on purpose:
--                        a run must outlive a permanently deleted project.
--   report_definitions   saved custom reports (the Builder's "Save") that people can re-run or schedule
--   report_schedules     reports that generate themselves daily / weekly / monthly (Oman time)
--   report_deliveries    the "new report" inbox: one row per recipient of a scheduled run
-- Who generated / viewed / downloaded what is written to the existing audit_log (entity 'Report'), not here.

CREATE TABLE IF NOT EXISTS report_runs (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_key       TEXT NOT NULL,                 -- catalogue key, or 'custom'
  title            TEXT NOT NULL,
  category         TEXT,
  version          INTEGER NOT NULL DEFAULT 1,    -- nth run of the same report for the same projects
  scope_sig        TEXT NOT NULL DEFAULT '',      -- report_key + sorted project ids: what "same report" means for versions
  source           TEXT NOT NULL DEFAULT 'adhoc', -- adhoc | scheduled
  schedule_id      INTEGER,
  definition_id    INTEGER,
  layout           TEXT NOT NULL DEFAULT 'standard',
  params           TEXT NOT NULL DEFAULT '{}',    -- JSON: what was asked for (scope, period, blocks …)
  scope_label      TEXT,
  project_count    INTEGER NOT NULL DEFAULT 0,
  period_from      TEXT,
  period_to        TEXT,
  as_of            TEXT,
  generated_by     TEXT,                          -- username
  generated_by_name TEXT,
  generated_at     TEXT NOT NULL DEFAULT utc_now_text(),
  snapshot         TEXT NOT NULL,                 -- the finished report (JSON)
  size_bytes       INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS report_runs_generated_idx ON report_runs (generated_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS report_runs_key_idx       ON report_runs (report_key);
CREATE INDEX IF NOT EXISTS report_runs_sig_idx       ON report_runs (scope_sig);

CREATE TABLE IF NOT EXISTS report_run_projects (
  run_id     INTEGER NOT NULL REFERENCES report_runs(id) ON DELETE CASCADE,
  project_id INTEGER NOT NULL,
  PRIMARY KEY (run_id, project_id)
);
CREATE INDEX IF NOT EXISTS report_run_projects_project_idx ON report_run_projects (project_id);

CREATE TABLE IF NOT EXISTS report_definitions (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT NOT NULL,
  description TEXT,
  blocks      TEXT NOT NULL DEFAULT '[]',   -- JSON list of block keys, in order
  params      TEXT NOT NULL DEFAULT '{}',   -- JSON: layout, period preset, business units / projects, statuses
  is_shared   INTEGER NOT NULL DEFAULT 0,   -- 1 = everyone with Report Library access sees it
  owner       TEXT NOT NULL,
  owner_name  TEXT,
  created_at  TEXT NOT NULL DEFAULT utc_now_text(),
  updated_at  TEXT NOT NULL DEFAULT utc_now_text()
);

CREATE TABLE IF NOT EXISTS report_schedules (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           TEXT NOT NULL,
  report_key     TEXT NOT NULL,             -- catalogue key, or 'custom' (then definition_id says which)
  definition_id  INTEGER,
  params         TEXT NOT NULL DEFAULT '{}',-- JSON: scope, relative period preset, layout
  frequency      TEXT NOT NULL,             -- daily | weekly | monthly
  weekday        INTEGER,                   -- weekly: 0 = Monday … 6 = Sunday
  month_day      INTEGER,                   -- monthly: 1–28, or 0 = last day of the month
  run_time       TEXT NOT NULL DEFAULT '07:00', -- HH:MM, Oman time
  recipients     TEXT NOT NULL DEFAULT '[]',-- JSON list of usernames
  active         INTEGER NOT NULL DEFAULT 1,
  next_run_at    TEXT,                      -- UTC ISO timestamp; NULL while paused
  last_run_at    TEXT,
  last_run_id    INTEGER,
  last_error     TEXT,
  created_by     TEXT NOT NULL,
  created_by_name TEXT,
  created_by_admin INTEGER NOT NULL DEFAULT 0,
  created_at     TEXT NOT NULL DEFAULT utc_now_text(),
  updated_at     TEXT NOT NULL DEFAULT utc_now_text()
);
CREATE INDEX IF NOT EXISTS report_schedules_due_idx ON report_schedules (next_run_at) WHERE active = 1;

CREATE TABLE IF NOT EXISTS report_deliveries (
  run_id       INTEGER NOT NULL REFERENCES report_runs(id) ON DELETE CASCADE,
  username     TEXT NOT NULL,
  schedule_id  INTEGER,
  delivered_at TEXT NOT NULL DEFAULT utc_now_text(),
  read_at      TEXT,
  PRIMARY KEY (run_id, username)
);
CREATE INDEX IF NOT EXISTS report_deliveries_user_idx ON report_deliveries (username, read_at);
