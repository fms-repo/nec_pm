CREATE TABLE IF NOT EXISTS project_resource_groups (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id   INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
