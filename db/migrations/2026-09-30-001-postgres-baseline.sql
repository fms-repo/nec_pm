-- Risk register: potential future events, scored Probability x Impact (1-5 each) with an
-- optional post-mitigation residual score. `severity` is legacy (pre-register model), kept only
-- so old rows still have a value.
CREATE TABLE IF NOT EXISTS risks (
  id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id            INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  title                 TEXT NOT NULL,
  severity              TEXT NOT NULL DEFAULT 'Medium',
  status                TEXT NOT NULL DEFAULT 'Open',
  raised_date           TEXT NOT NULL DEFAULT utc_today_text(),
  description           TEXT,
  category              TEXT NOT NULL DEFAULT 'Other',
  owner                 TEXT,
  mitigation_target     TEXT,
  probability           INTEGER NOT NULL DEFAULT 3,
  impact                INTEGER NOT NULL DEFAULT 3,
  response_strategy     TEXT,
  mitigation_plan       TEXT,
  residual_probability  INTEGER,
  residual_impact       INTEGER,
  is_critical           INTEGER NOT NULL DEFAULT 0,
  triggers              TEXT,
  contingency_plan      TEXT,
  remarks               TEXT,
  created_at            TEXT NOT NULL DEFAULT utc_now_text(),
  updated_at            TEXT NOT NULL DEFAULT utc_now_text()
);

-- Issue log: problems that have already occurred (RAID-log "Issues"), tracked to resolution.
-- May optionally trace back to the risk that materialized. `owner` is shown as "Assigned To".
CREATE TABLE IF NOT EXISTS issues (
  id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id              INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  title                   TEXT NOT NULL,
  description             TEXT,
  category                TEXT NOT NULL DEFAULT 'Other',
  owner                   TEXT,
  raised_by               TEXT,
  priority                TEXT NOT NULL DEFAULT 'Medium',
  severity                TEXT NOT NULL DEFAULT 'Medium',
  status                  TEXT NOT NULL DEFAULT 'Open',
  raised_date             TEXT NOT NULL DEFAULT utc_today_text(),
  target_resolution_date  TEXT,
  actual_resolution_date  TEXT,
  impact_description      TEXT,
  root_cause              TEXT,
  resolution_plan         TEXT,
  verification_notes      TEXT,
  related_risk_id         INTEGER REFERENCES risks(id) ON DELETE SET NULL,
  is_escalated            INTEGER NOT NULL DEFAULT 0,
  remarks                 TEXT,
  created_at              TEXT NOT NULL DEFAULT utc_now_text(),
  updated_at              TEXT NOT NULL DEFAULT utc_now_text()
);

