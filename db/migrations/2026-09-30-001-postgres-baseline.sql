-- (filename under uploads/business-unit-logos/, served via /api/business-units/:id/logo) is the
-- letterhead shown on print documents.
CREATE TABLE IF NOT EXISTS business_units (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL UNIQUE,
  logo_path  TEXT
);

-- Team directory (company users), shared across all projects. project_members assigns
