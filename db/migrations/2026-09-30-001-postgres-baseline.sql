-- Project Resources: internal members (assigned from team_members), external parties, and
-- groups that organize both. member_type + member_id on group entries is a polymorphic
-- reference (same pattern as invoice_items.source_type/source_id) rather than two FK columns.
CREATE TABLE IF NOT EXISTS project_members (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id      INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  team_member_id  INTEGER NOT NULL REFERENCES team_members(id) ON DELETE CASCADE,
  added_at        TEXT NOT NULL DEFAULT utc_now_text(),
  UNIQUE (project_id, team_member_id)
);

-- A project can span more than one governorate/location. projects.governorate_id stays the
-- "primary" location; this table holds the full set.
CREATE TABLE IF NOT EXISTS project_governorates (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id      INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  governorate_id  INTEGER NOT NULL REFERENCES governorates(id) ON DELETE CASCADE,
  UNIQUE (project_id, governorate_id)
);

-- Sub Contractors: a project's secondary contractors, distinct from the primary Contractor
-- (projects.contractor_id).
CREATE TABLE IF NOT EXISTS project_subcontractors (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id      INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  contractor_id   INTEGER NOT NULL REFERENCES contractors(id) ON DELETE CASCADE,
  UNIQUE (project_id, contractor_id)
);

CREATE TABLE IF NOT EXISTS project_external_parties (
