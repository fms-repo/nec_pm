-- Migration 2026-09-30-001: PostgreSQL baseline — the full schema as it stood when the app
-- moved from SQLite (every table/column of the final SQLite schema). Written idempotently
-- (IF NOT EXISTS / CREATE OR REPLACE) so it is also safe on a database whose tables were
-- already created before migrations were tracked. Applied once by db/migrate.js.
--
-- Type choices mirror the SQLite database this replaced, so the app's behaviour is unchanged:
--   * amounts/quantities are DOUBLE PRECISION (SQLite REAL);
--   * dates are TEXT 'YYYY-MM-DD' and timestamps TEXT 'YYYY-MM-DD HH:MM:SS' (UTC), exactly the
--     strings the API has always returned and the front-end/print pages parse;
--   * yes/no flags are INTEGER 0/1.

-- Current UTC timestamp / date as text, same format SQLite's datetime('now') / date('now') gave.
CREATE OR REPLACE FUNCTION utc_now_text() RETURNS TEXT LANGUAGE sql STABLE AS
$$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') $$;
CREATE OR REPLACE FUNCTION utc_today_text() RETURNS TEXT LANGUAGE sql STABLE AS
$$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD') $$;

