-- quantity = Planned Qty; actual_qty = Actual Qty (a crew's equivalent of a material's
-- Consumed Qty) — actual labour cost is priced from it.
CREATE TABLE IF NOT EXISTS project_crews (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id      INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  event_id        INTEGER REFERENCES project_events(id) ON DELETE SET NULL,
  stage           TEXT NOT NULL DEFAULT 'Execution / Construction',
  resource_type   TEXT NOT NULL DEFAULT 'Labour',
  resource_name   TEXT NOT NULL,
  contractor_id   INTEGER REFERENCES contractors(id),
  quantity        DOUBLE PRECISION NOT NULL DEFAULT 1,
  actual_qty      DOUBLE PRECISION NOT NULL DEFAULT 0,
  rate_basis      TEXT NOT NULL DEFAULT 'Per Day',
  unit_rate       DOUBLE PRECISION NOT NULL DEFAULT 0,
  allocated_days  DOUBLE PRECISION NOT NULL DEFAULT 0,
  start_date      TEXT,
  end_date        TEXT,
  status          TEXT NOT NULL DEFAULT 'Planned',
  notes           TEXT
);

-- Invoices are generated from a selection of a project's material/crew cost line items.
-- invoice_items snapshot their description/qty/rate at creation time (not a live join) so an
-- invoice never silently changes if the source row is edited or deleted afterwards.
CREATE TABLE IF NOT EXISTS invoices (
  id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id           INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  invoice_number       TEXT NOT NULL UNIQUE,
  invoice_date         TEXT NOT NULL DEFAULT utc_today_text(),
  due_date             TEXT,
  status               TEXT NOT NULL DEFAULT 'Draft',
  bill_from_name       TEXT,
  bill_from_address    TEXT,
  bill_from_contact    TEXT,
  bill_to_name         TEXT,
  bill_to_address      TEXT,
  bill_to_contact      TEXT,
  margin_mode          TEXT NOT NULL DEFAULT 'line',
  global_margin_type   TEXT NOT NULL DEFAULT 'percent',
  global_margin_value  DOUBLE PRECISION NOT NULL DEFAULT 0,
  vat_rate             DOUBLE PRECISION NOT NULL DEFAULT 5,
  payment_terms        TEXT,
  bank_details         TEXT,
  notes                TEXT,
  subtotal             DOUBLE PRECISION NOT NULL DEFAULT 0,
  margin_total         DOUBLE PRECISION NOT NULL DEFAULT 0,
  vat_amount           DOUBLE PRECISION NOT NULL DEFAULT 0,
  grand_total          DOUBLE PRECISION NOT NULL DEFAULT 0,
  created_at           TEXT NOT NULL DEFAULT utc_now_text(),
  updated_at           TEXT NOT NULL DEFAULT utc_now_text()
);

CREATE TABLE IF NOT EXISTS invoice_items (
