-- Change management (integrated change control): a Change Request moves through Initial
-- Analysis (impact assessment) to a Change Control Board decision. CR status is derived, not
-- stored. cr_type is the Change Category; cr_source is the CR Type (Client / Subcontractor).
CREATE TABLE IF NOT EXISTS change_requests (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id          INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  cr_code             TEXT NOT NULL UNIQUE,
  cr_type             TEXT NOT NULL DEFAULT 'Scope',
  cr_source           TEXT NOT NULL DEFAULT 'Client',
  subcontractor_id    INTEGER REFERENCES contractors(id),
  submitter_name      TEXT,
  description         TEXT NOT NULL,
  date_submitted      TEXT NOT NULL DEFAULT utc_today_text(),
  date_required       TEXT,
  priority            TEXT NOT NULL DEFAULT 'Medium',
  reason_for_change   TEXT,
  assumptions_notes   TEXT,
  comments            TEXT,
  created_at          TEXT NOT NULL DEFAULT utc_now_text(),
  updated_at          TEXT NOT NULL DEFAULT utc_now_text()
);

CREATE TABLE IF NOT EXISTS change_analyses (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  change_request_id  INTEGER NOT NULL REFERENCES change_requests(id) ON DELETE CASCADE,
  category           TEXT NOT NULL DEFAULT 'Other',
  sub_category       TEXT,
  hour_impact        DOUBLE PRECISION NOT NULL DEFAULT 0,  -- retired (no longer shown/edited), kept for history
  duration_impact    DOUBLE PRECISION NOT NULL DEFAULT 0,  -- retired: superseded by duration_months + duration_days
  duration_months    INTEGER NOT NULL DEFAULT 0,
  duration_days      INTEGER NOT NULL DEFAULT 0,
  schedule_impact    TEXT NOT NULL DEFAULT 'No',  -- 'Yes' | 'No'
  cost_impact        DOUBLE PRECISION NOT NULL DEFAULT 0,
  comments           TEXT,
  recommendations    TEXT,
  created_at         TEXT NOT NULL DEFAULT utc_now_text(),
  updated_at         TEXT NOT NULL DEFAULT utc_now_text()
);

CREATE TABLE IF NOT EXISTS change_decisions (
  id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  change_request_id        INTEGER NOT NULL REFERENCES change_requests(id) ON DELETE CASCADE,
  decision                 TEXT NOT NULL DEFAULT 'Approved',
  decision_date            TEXT NOT NULL DEFAULT utc_today_text(),
